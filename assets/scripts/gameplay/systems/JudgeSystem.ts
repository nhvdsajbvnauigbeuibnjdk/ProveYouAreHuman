export class JudgeSystem {
    public generate(level: LevelDefinition, result: LevelValidationResult, saveData: Readonly<SaveData>): string {
        const pool = this.resolvePool(level.type, result.reasonKey, result.success);
        const seed = this.buildSeed(level, result, saveData);
        const verdict = pool[seed % pool.length] ?? pool[0] ?? GENERIC_FAILURE_POOL[0];
        const suffix = result.success
            ? `\u5f53\u524d\u4eba\u7c7b\u6307\u6570\uff1a${saveData.stats.humanScore}\u3002`
            : `\u5f53\u524d\u4eba\u7c7b\u6307\u6570\uff1a${saveData.stats.humanScore}\uff0c\u8fde\u7eed\u5931\u8d25\uff1a${saveData.stats.consecutiveFailures}\u3002`;

        return `${verdict} ${suffix}`;
    }

    private resolvePool(levelType: LevelType, reasonKey: string, success: boolean): string[] {
        const levelPool = this.getLevelPool(levelType);
        const fallbackKey = success ? 'success' : 'failure';
        return levelPool[reasonKey] ?? levelPool[fallbackKey] ?? (success ? GENERIC_SUCCESS_POOL : GENERIC_FAILURE_POOL);
    }

    private getLevelPool(levelType: LevelType): JudgePoolMap {
        switch (levelType) {
        case LevelType.SelectImage:
            return SELECT_IMAGE_POOL;
        case LevelType.FakeButton:
            return FAKE_BUTTON_POOL;
        case LevelType.ReverseSlider:
            return REVERSE_SLIDER_POOL;
        default:
            return {
                success: GENERIC_SUCCESS_POOL,
                failure: GENERIC_FAILURE_POOL,
            };
        }
    }

    private buildSeed(level: LevelDefinition, result: LevelValidationResult, saveData: Readonly<SaveData>): number {
        return Math.abs(
            level.id * 31
            + saveData.stats.totalAttempts * 17
            + saveData.stats.totalFailures * 13
            + result.reasonKey.length * 7,
        );
    }
}

export const judgeSystem = new JudgeSystem();
